// Ícones em pixel art, desenhados numa grade de 12x12 (cada "#" é um pixel).
import type { SVGProps } from "react";
import { RECYCLE_PIXELS } from "@/lib/sprite";

type P = SVGProps<SVGSVGElement>;

/** Converte as linhas do desenho em retângulos, juntando pixels vizinhos. */
function pixelRects(rows: string[]) {
  const rects: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let end = x;
      while (row[end] === "#") end++;
      rects.push({ x, y, w: end - x });
      x = end;
    }
  });
  return rects;
}

function pixelIcon(rows: string[]) {
  const rects = pixelRects(rows);
  // A grade pode ter qualquer tamanho; o desenho se ajusta a ela.
  const cols = Math.max(...rows.map((r) => r.length));
  const lines = rows.length;
  return function PixelIcon(props: P) {
    return (
      <svg
        width="20"
        height="20"
        viewBox={`0 0 ${cols} ${lines}`}
        fill="currentColor"
        shapeRendering="crispEdges"
        aria-hidden="true"
        {...props}
      >
        {rects.map((r) => (
          <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={r.w} height={1} />
        ))}
      </svg>
    );
  };
}

